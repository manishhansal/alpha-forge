/**
 * promotion.ts — Strategy Promotion Engine
 *
 * Enforces the gating rules that control when a strategy arm can advance
 * through the experiment pipeline:
 *
 *   RESEARCH → BACKTEST   (no gate — instant)
 *   BACKTEST → SHADOW     (no gate — instant)
 *   SHADOW   → PAPER      minimum sample requirements must be met
 *   PAPER    → LIVE       REQUIRES explicit human approval token
 *                         ⛔ NEVER auto-promoted — this is a hard invariant
 *
 * Sample-size gates (SHADOW → PAPER)
 * ────────────────────────────────────
 *   • minimumTrades           — closed shadow trades (default 50)
 *   • minimumObservationDays  — calendar days the shadow has been running (default 10)
 *   • minimumSharpe           — annualised Sharpe must be above this floor (default 0)
 *   • maximumDrawdown         — max drawdown must be below this ceiling (default 0.25)
 *   • minimumWinRate          — win rate floor (default 0, i.e. no floor by default)
 *
 * Approval tokens (PAPER → LIVE)
 * ────────────────────────────────
 * A token is a random 32-byte hex string generated by `issueApprovalToken()`.
 * Tokens are single-use and expire after `tokenTtlMs` (default 24 hours).
 * The token must be passed to `approveLivePromotion()`.
 * Even after a valid token is supplied the caller must explicitly call
 * `ExperimentManager.promoteArm()` — the PromotionEngine only validates, it
 * never mutates experiment state directly.
 */

import type { ShadowSummary } from "./shadow-trader";
import type { ExperimentMode } from "./experiment-manager";

// ── Gate configuration ─────────────────────────────────────────────────────────

export interface ShadowToPaperGates {
  /** Minimum closed shadow trades. Default 50. */
  minimumTrades: number;
  /** Minimum calendar days running in SHADOW. Default 10. */
  minimumObservationDays: number;
  /** Minimum annualised Sharpe ratio. Default 0 (no floor). */
  minimumSharpe: number;
  /** Maximum drawdown allowed (0..1). Default 0.25. */
  maximumDrawdown: number;
  /** Minimum win rate (0..1). Default 0 (no floor). */
  minimumWinRate: number;
  /** Minimum profit factor. Default 0 (no floor). */
  minimumProfitFactor: number;
}

export const DEFAULT_SHADOW_TO_PAPER_GATES: ShadowToPaperGates = {
  minimumTrades: 50,
  minimumObservationDays: 10,
  minimumSharpe: 0,
  maximumDrawdown: 0.25,
  minimumWinRate: 0,
  minimumProfitFactor: 0,
};

export interface PromotionEngineConfig {
  shadowToPaper?: Partial<ShadowToPaperGates>;
  /** Token TTL in milliseconds. Default 86_400_000 (24 hours). */
  tokenTtlMs?: number;
}

// ── Promotion check result ─────────────────────────────────────────────────────

export type PromotionCheckStatus =
  | "ELIGIBLE"          // All gates passed — promotion is allowed
  | "INELIGIBLE"        // One or more gates failed
  | "REQUIRES_APPROVAL" // PAPER → LIVE path — manual token required
  | "INVALID_TRANSITION"; // Not a valid stage transition

export interface GateResult {
  gate: string;
  passed: boolean;
  required: number | string;
  actual: number | string;
  detail: string;
}

export interface PromotionCheckResult {
  experimentId: string;
  armId: string;
  fromMode: ExperimentMode;
  toMode: ExperimentMode;
  status: PromotionCheckStatus;
  gates: GateResult[];
  /** Human-readable summary of what is blocking promotion (if any). */
  blockers: string[];
  /** How close the arm is to meeting all gates (0..1). */
  readinessFraction: number;
  checkedAtMs: number;
}

// ── Approval token ─────────────────────────────────────────────────────────────

export interface ApprovalToken {
  token: string;
  experimentId: string;
  armId: string;
  /** UTC ms when the token was issued. */
  issuedAtMs: number;
  /** UTC ms after which the token is invalid. */
  expiresAtMs: number;
  /** UTC ms when the token was consumed (null = not yet used). */
  consumedAtMs: number | null;
  /** Identity of the human who issued the token (free-form). */
  issuedBy: string;
  /** Reason / justification recorded at issuance. */
  justification: string;
}

// ── Audit record ───────────────────────────────────────────────────────────────

export type PromotionEventType =
  | "CHECK_PERFORMED"
  | "TOKEN_ISSUED"
  | "TOKEN_CONSUMED"
  | "TOKEN_EXPIRED"
  | "TOKEN_REJECTED"
  | "PROMOTION_APPROVED"
  | "PROMOTION_REJECTED";

export interface PromotionAuditRecord {
  id: string;
  timestampMs: number;
  type: PromotionEventType;
  experimentId: string;
  armId: string;
  fromMode: ExperimentMode;
  toMode: ExperimentMode;
  detail: string;
  actorId?: string;
}

// ── PromotionEngine ────────────────────────────────────────────────────────────

export class PromotionEngine {
  private readonly _gates: ShadowToPaperGates;
  private readonly _tokenTtlMs: number;
  private readonly _tokens = new Map<string, ApprovalToken>();
  private readonly _auditLog: PromotionAuditRecord[] = [];
  private _auditCounter = 0;

  constructor(config: PromotionEngineConfig = {}) {
    this._gates = {
      ...DEFAULT_SHADOW_TO_PAPER_GATES,
      ...(config.shadowToPaper ?? {}),
    };
    this._tokenTtlMs = config.tokenTtlMs ?? 86_400_000; // 24 h
  }

  // ── Gate checking ──────────────────────────────────────────────────────

  /**
   * Check whether an arm is eligible for promotion to `toMode`.
   *
   * This is a read-only operation — it never mutates experiment state.
   * Callers should call this before `ExperimentManager.promoteArm()`.
   */
  checkPromotion(
    experimentId: string,
    armId: string,
    fromMode: ExperimentMode,
    toMode: ExperimentMode,
    summary: ShadowSummary,
    shadowStartedAtMs: number,
  ): PromotionCheckResult {
    const checkedAtMs = Date.now();

    // Validate transition direction
    if (!isValidTransition(fromMode, toMode)) {
      this._audit("CHECK_PERFORMED", experimentId, armId, fromMode, toMode,
        `Invalid transition ${fromMode}→${toMode}`);
      return {
        experimentId, armId, fromMode, toMode,
        status: "INVALID_TRANSITION",
        gates: [],
        blockers: [`${fromMode} → ${toMode} is not a valid transition`],
        readinessFraction: 0,
        checkedAtMs,
      };
    }

    // PAPER → LIVE: always requires manual approval
    if (fromMode === "PAPER" && toMode === "LIVE") {
      this._audit("CHECK_PERFORMED", experimentId, armId, fromMode, toMode,
        "PAPER→LIVE requires manual approval token");
      return {
        experimentId, armId, fromMode, toMode,
        status: "REQUIRES_APPROVAL",
        gates: [],
        blockers: [
          "PAPER → LIVE promotion requires an explicit human-issued approval token. " +
            "Call issueApprovalToken() and then approveLivePromotion().",
        ],
        readinessFraction: 1, // gates are met — only human approval remains
        checkedAtMs,
      };
    }

    // SHADOW → PAPER: evaluate sample-size gates
    if (fromMode === "SHADOW" && toMode === "PAPER") {
      const observationDays =
        (checkedAtMs - shadowStartedAtMs) / (24 * 60 * 60 * 1000);

      const gates: GateResult[] = [
        makeGate(
          "minimum_trades",
          summary.totalTrades >= this._gates.minimumTrades,
          this._gates.minimumTrades,
          summary.totalTrades,
          `Closed shadow trades: ${summary.totalTrades} / ${this._gates.minimumTrades} required`,
        ),
        makeGate(
          "observation_days",
          observationDays >= this._gates.minimumObservationDays,
          this._gates.minimumObservationDays,
          +observationDays.toFixed(1),
          `Observation days: ${observationDays.toFixed(1)} / ${this._gates.minimumObservationDays} required`,
        ),
        makeGate(
          "minimum_sharpe",
          summary.sharpe >= this._gates.minimumSharpe,
          this._gates.minimumSharpe,
          +summary.sharpe.toFixed(3),
          `Sharpe: ${summary.sharpe.toFixed(3)} / ${this._gates.minimumSharpe} required`,
        ),
        makeGate(
          "maximum_drawdown",
          summary.maxDrawdownPct / 100 <= this._gates.maximumDrawdown,
          `≤ ${(this._gates.maximumDrawdown * 100).toFixed(0)}%`,
          `${summary.maxDrawdownPct.toFixed(1)}%`,
          `Max drawdown: ${summary.maxDrawdownPct.toFixed(1)}% (limit ${(this._gates.maximumDrawdown * 100).toFixed(0)}%)`,
        ),
        makeGate(
          "minimum_win_rate",
          summary.winRate >= this._gates.minimumWinRate,
          this._gates.minimumWinRate,
          +summary.winRate.toFixed(3),
          `Win rate: ${(summary.winRate * 100).toFixed(1)}% / ${(this._gates.minimumWinRate * 100).toFixed(1)}% required`,
        ),
        makeGate(
          "minimum_profit_factor",
          summary.profitFactor >= this._gates.minimumProfitFactor,
          this._gates.minimumProfitFactor,
          +summary.profitFactor.toFixed(3),
          `Profit factor: ${summary.profitFactor.toFixed(3)} / ${this._gates.minimumProfitFactor} required`,
        ),
      ];

      const passed = gates.filter((g) => g.passed).length;
      const total = gates.length;
      const readinessFraction = total > 0 ? passed / total : 0;
      const blockers = gates.filter((g) => !g.passed).map((g) => g.detail);
      const status: PromotionCheckStatus =
        blockers.length === 0 ? "ELIGIBLE" : "INELIGIBLE";

      this._audit("CHECK_PERFORMED", experimentId, armId, fromMode, toMode,
        status === "ELIGIBLE"
          ? "All gates passed — eligible for SHADOW→PAPER promotion"
          : `Blocked by ${blockers.length} gate(s): ${blockers.join("; ")}`);

      return {
        experimentId, armId, fromMode, toMode,
        status, gates, blockers, readinessFraction, checkedAtMs,
      };
    }

    // All other transitions (RESEARCH→BACKTEST, BACKTEST→SHADOW) are ungated
    this._audit("CHECK_PERFORMED", experimentId, armId, fromMode, toMode,
      `${fromMode}→${toMode} transition has no gates — eligible`);
    return {
      experimentId, armId, fromMode, toMode,
      status: "ELIGIBLE",
      gates: [],
      blockers: [],
      readinessFraction: 1,
      checkedAtMs,
    };
  }

  // ── Approval tokens ────────────────────────────────────────────────────

  /**
   * Issue a single-use approval token for PAPER → LIVE promotion.
   *
   * The token should be generated by a human operator after reviewing the
   * paper trading results and risk parameters. It expires after `tokenTtlMs`.
   *
   * ⛔ This method does NOT perform the promotion — it only issues a token.
   *    The human must then call `approveLivePromotion()` with this token.
   */
  issueApprovalToken(
    experimentId: string,
    armId: string,
    issuedBy: string,
    justification: string,
  ): ApprovalToken {
    if (!justification || justification.trim().length < 10) {
      throw new Error(
        "[PromotionEngine] Approval token requires a non-trivial justification (≥10 chars)",
      );
    }
    if (!issuedBy || issuedBy.trim().length === 0) {
      throw new Error("[PromotionEngine] Approval token requires an issuedBy identity");
    }

    const token = generateToken();
    const now = Date.now();
    const record: ApprovalToken = {
      token,
      experimentId,
      armId,
      issuedAtMs: now,
      expiresAtMs: now + this._tokenTtlMs,
      consumedAtMs: null,
      issuedBy: issuedBy.trim(),
      justification: justification.trim(),
    };

    this._tokens.set(token, record);

    this._audit("TOKEN_ISSUED", experimentId, armId, "PAPER", "LIVE",
      `Token issued by ${issuedBy}: ${justification.slice(0, 80)}`,
      issuedBy);

    return record;
  }

  /**
   * Validate and consume an approval token for PAPER → LIVE promotion.
   *
   * Returns the token record if valid. Throws if:
   *   • Token not found
   *   • Token already consumed
   *   • Token expired
   *   • Token is for a different experiment/arm
   *
   * After this call the token is marked consumed and cannot be reused.
   * The caller should then invoke `ExperimentManager.promoteArm()` with the
   * token string to complete the promotion.
   */
  approveLivePromotion(
    token: string,
    experimentId: string,
    armId: string,
    approvedBy: string,
  ): ApprovalToken {
    const record = this._tokens.get(token);

    if (!record) {
      this._auditRejection(experimentId, armId, token, "Token not found");
      throw new Error("[PromotionEngine] Invalid approval token — not found");
    }

    if (record.consumedAtMs !== null) {
      this._auditRejection(experimentId, armId, token,
        `Token already consumed at ${new Date(record.consumedAtMs).toISOString()}`);
      throw new Error("[PromotionEngine] Approval token has already been consumed");
    }

    if (Date.now() > record.expiresAtMs) {
      record.consumedAtMs = Date.now(); // mark consumed so it can't be used again
      this._audit("TOKEN_EXPIRED", experimentId, armId, "PAPER", "LIVE",
        `Token expired at ${new Date(record.expiresAtMs).toISOString()}`);
      throw new Error(
        `[PromotionEngine] Approval token expired at ${new Date(record.expiresAtMs).toISOString()}`,
      );
    }

    if (record.experimentId !== experimentId || record.armId !== armId) {
      this._auditRejection(experimentId, armId, token,
        `Token is for experiment=${record.experimentId} arm=${record.armId}`);
      throw new Error(
        "[PromotionEngine] Approval token was issued for a different experiment/arm",
      );
    }

    // Consume the token (single-use)
    record.consumedAtMs = Date.now();

    this._audit("TOKEN_CONSUMED", experimentId, armId, "PAPER", "LIVE",
      `Token consumed by ${approvedBy} — LIVE promotion approved`,
      approvedBy);
    this._audit("PROMOTION_APPROVED", experimentId, armId, "PAPER", "LIVE",
      `Manual LIVE promotion approved by ${approvedBy}`,
      approvedBy);

    return record;
  }

  /**
   * Reject a LIVE promotion attempt without a valid token.
   * Records an audit entry and throws with a descriptive error.
   *
   * Called by integrations that attempt auto-promotion to LIVE to surface
   * the violation loudly.
   */
  rejectAutoLivePromotion(experimentId: string, armId: string): never {
    this._audit("PROMOTION_REJECTED", experimentId, armId, "PAPER", "LIVE",
      "AUTO-PROMOTION TO LIVE REJECTED — explicit human approval required");
    throw new Error(
      "[PromotionEngine] AUTO-PROMOTION TO LIVE IS STRICTLY FORBIDDEN. " +
        "A human operator must issue an approval token via issueApprovalToken() " +
        "and then call approveLivePromotion() to complete the transition.",
    );
  }

  // ── Readiness summary (for dashboard) ─────────────────────────────────

  /**
   * Returns a progress snapshot for a shadow arm showing how close it is
   * to meeting all SHADOW → PAPER gates.
   */
  readinessSummary(
    experimentId: string,
    armId: string,
    summary: ShadowSummary,
    shadowStartedAtMs: number,
  ): ReadinessSummary {
    const check = this.checkPromotion(
      experimentId,
      armId,
      "SHADOW",
      "PAPER",
      summary,
      shadowStartedAtMs,
    );

    const observationDays =
      (Date.now() - shadowStartedAtMs) / (24 * 60 * 60 * 1000);

    return {
      experimentId,
      armId,
      eligible: check.status === "ELIGIBLE",
      readinessFraction: check.readinessFraction,
      gates: check.gates,
      blockers: check.blockers,
      sampleProgress: {
        trades: summary.totalTrades,
        requiredTrades: this._gates.minimumTrades,
        tradeFraction: Math.min(1, summary.totalTrades / this._gates.minimumTrades),
        observationDays: +observationDays.toFixed(1),
        requiredDays: this._gates.minimumObservationDays,
        dayFraction: Math.min(
          1,
          observationDays / this._gates.minimumObservationDays,
        ),
      },
    };
  }

  // ── Accessors ──────────────────────────────────────────────────────────

  auditLog(): PromotionAuditRecord[] {
    return [...this._auditLog];
  }

  listTokens(): ApprovalToken[] {
    return Array.from(this._tokens.values());
  }

  getToken(token: string): ApprovalToken | undefined {
    return this._tokens.get(token);
  }

  // ── Private helpers ────────────────────────────────────────────────────

  private _audit(
    type: PromotionEventType,
    experimentId: string,
    armId: string,
    fromMode: ExperimentMode,
    toMode: ExperimentMode,
    detail: string,
    actorId?: string,
  ): void {
    this._auditLog.push({
      id: `paudit_${(++this._auditCounter).toString(36).padStart(8, "0")}`,
      timestampMs: Date.now(),
      type,
      experimentId,
      armId,
      fromMode,
      toMode,
      detail,
      actorId,
    });
  }

  private _auditRejection(
    experimentId: string,
    armId: string,
    token: string,
    reason: string,
  ): void {
    this._audit("TOKEN_REJECTED", experimentId, armId, "PAPER", "LIVE",
      `Token rejected (${token.slice(0, 8)}…): ${reason}`);
  }
}

// ── Readiness summary type ─────────────────────────────────────────────────────

export interface ReadinessSummary {
  experimentId: string;
  armId: string;
  eligible: boolean;
  /** 0..1 fraction of gates passed. */
  readinessFraction: number;
  gates: GateResult[];
  blockers: string[];
  sampleProgress: {
    trades: number;
    requiredTrades: number;
    tradeFraction: number;
    observationDays: number;
    requiredDays: number;
    dayFraction: number;
  };
}

// ── Pure helpers ───────────────────────────────────────────────────────────────

function isValidTransition(from: ExperimentMode, to: ExperimentMode): boolean {
  const allowed: Record<ExperimentMode, ExperimentMode[]> = {
    RESEARCH: ["BACKTEST"],
    BACKTEST: ["SHADOW"],
    SHADOW: ["PAPER"],
    PAPER: ["LIVE"],
    LIVE: [],
  };
  return allowed[from]?.includes(to) ?? false;
}

function makeGate(
  gate: string,
  passed: boolean,
  required: number | string,
  actual: number | string,
  detail: string,
): GateResult {
  return { gate, passed, required, actual, detail };
}

/**
 * Generate a 32-byte random hex token.
 * Uses crypto.getRandomValues when available (browser/Node 19+), otherwise
 * falls back to Math.random for test environments.
 */
function generateToken(): string {
  if (
    typeof globalThis.crypto !== "undefined" &&
    typeof globalThis.crypto.getRandomValues === "function"
  ) {
    const buf = new Uint8Array(32);
    globalThis.crypto.getRandomValues(buf);
    return Array.from(buf)
      .map((b) => b.toString(16).padStart(2, "0"))
      .join("");
  }
  // Fallback for environments without Web Crypto
  return Array.from({ length: 32 }, () =>
    Math.floor(Math.random() * 256).toString(16).padStart(2, "0"),
  ).join("");
}

// ── Module-level singleton ─────────────────────────────────────────────────────

export const globalPromotionEngine = new PromotionEngine();
